CREATE TABLE STUDENT (StudentID INT PRIMARY KEY, StudentName TEXT, StudentMajor TEXT);
CREATE TABLE SUPERVISOR (SupervisorID INT PRIMARY KEY, SupervisorName TEXT, SupervisorDept TEXT);
CREATE TABLE PROJECT (ProjectID INT PRIMARY KEY, ProjectTitle TEXT, ProjectType TEXT,
  SupervisorID INT REFERENCES SUPERVISOR);
CREATE TABLE WORK (StudentID INT REFERENCES STUDENT, ProjectID INT REFERENCES PROJECT,
  Role TEXT, HoursWorked INT, StartDate DATE, EndDate DATE, PRIMARY KEY (StudentID, ProjectID));

CREATE TABLE STUDENT2 (StudentID INT PRIMARY KEY, StudentMajor TEXT);
CREATE TABLE COURSE2 (CourseID INT PRIMARY KEY, CourseName TEXT);
CREATE TABLE INSTRUCTOR2 (InstructorID INT PRIMARY KEY, InstructorName TEXT);
CREATE TABLE ROOM2 (Room TEXT PRIMARY KEY, Building TEXT);
CREATE TABLE SECTION (CourseID INT REFERENCES COURSE2, TimeSlot TEXT, InstructorID INT REFERENCES INSTRUCTOR2,
  Room TEXT REFERENCES ROOM2, PRIMARY KEY (CourseID, TimeSlot));
CREATE TABLE ENROLLMENT (StudentID INT REFERENCES STUDENT2, CourseID INT, TimeSlot TEXT,
  FOREIGN KEY (CourseID, TimeSlot) REFERENCES SECTION, PRIMARY KEY (StudentID, CourseID, TimeSlot));


CREATE TABLE STUDENT3 (SID INT PRIMARY KEY, Name TEXT);
CREATE TABLE FACULTY (FID INT PRIMARY KEY, Name TEXT);
CREATE TABLE ROOM3 (RoomID INT PRIMARY KEY, Bldg TEXT);
CREATE TABLE CLUB (ClubID INT PRIMARY KEY, Name TEXT, Budget NUMERIC, AdvisorID INT REFERENCES FACULTY);
CREATE TABLE MEMBERSHIP (SID INT REFERENCES STUDENT3, ClubID INT REFERENCES CLUB,
  Position TEXT, JoinDate DATE, PRIMARY KEY (SID, ClubID));
CREATE TABLE EVENT (EventID INT PRIMARY KEY, ClubID INT REFERENCES CLUB, RoomID INT REFERENCES ROOM3, DateTime TIMESTAMP);
CREATE TABLE ATTENDANCE (SID INT REFERENCES STUDENT3, EventID INT REFERENCES EVENT, PRIMARY KEY (SID, EventID));
CREATE TABLE EXPENSE (ExpID INT PRIMARY KEY, ClubID INT REFERENCES CLUB, Amount NUMERIC, ExpDate DATE);
